#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."
module="$(go list -m)"
out="plugins/plugins.go"

{
  echo "// Code generated by scripts/gen-plugins.sh; DO NOT EDIT."
  echo
  echo "package plugins"
  echo
  echo "import ("
  for dir in plugins/*/; do
    dir="${dir%/}"
    if ls "$dir"/*.go >/dev/null 2>&1; then
      echo "	_ \"$module/$dir\""
    fi
  done
  echo ")"
} > "$out"
gofmt -w "$out"
echo "Generated $out"
